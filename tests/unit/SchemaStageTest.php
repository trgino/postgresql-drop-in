<?php
declare( strict_types=1 );

namespace Slonik\Tests\Unit;

use PHPUnit\Framework\TestCase;
use Slonik\Migrate\SchemaStage;
use Slonik\Sql\TranslationException;

final class SchemaStageTest extends TestCase {

	private const FIXTURE = "CREATE TABLE `wp_demos1` (\n"
		. "\t`id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,\n"
		. "\t`post_author` bigint(20) unsigned NOT NULL DEFAULT 0,\n"
		. "\t`post_date` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,\n"
		. "\t`post_title` text NOT NULL,\n"
		. "\t`status` enum('draft','live') NOT NULL DEFAULT 'draft',\n"
		. "\tPRIMARY KEY (`id`),\n"
		. "\tKEY `post_name` (`post_author`),\n"
		. "\tFULLTEXT KEY `search_key` (`post_title`),\n"
		. "\tCONSTRAINT `wp_demos1_ibfk_1` FOREIGN KEY (`post_author`) REFERENCES `wp_users` (`ID`)\n"
		. ") ENGINE=InnoDB AUTO_INCREMENT=766 DEFAULT CHARSET=utf8mb4";

	public function test_stage_splits_table_indexes_and_comments(): void {
		$out = SchemaStage::stage( self::FIXTURE );
		$this->assertStringStartsWith( 'CREATE TABLE "wp_demos1" (', $out['table'] );
		$this->assertStringContainsString( 'PRIMARY KEY ("id")', $out['table'] );
		$this->assertStringContainsString( 'GENERATED BY DEFAULT AS IDENTITY', $out['table'] );
		$this->assertStringContainsString( 'timestamp(0)', $out['table'] );
		$this->assertCount( 3, $out['extra'] );
		$this->assertSame( 'CREATE INDEX IF NOT EXISTS "wp_demos1__post_name" ON "wp_demos1" ("post_author")', $out['extra'][0] );
		// ON UPDATE CURRENT_TIMESTAMP becomes a trigger in the final phase.
		$this->assertStringContainsString( 'CREATE OR REPLACE FUNCTION', $out['extra'][1] );
		$this->assertStringContainsString( 'CREATE OR REPLACE TRIGGER "wp_demos1__post_date_update"', $out['extra'][2] );
		$this->assertCount( 5, $out['comments'] );
		$this->assertStringContainsString( 'COMMENT ON COLUMN', $out['comments'][0] );
	}

	public function test_fulltext_and_fk_notice_but_do_not_break_table(): void {
		$out = SchemaStage::stage( self::FIXTURE );
		$this->assertCount( 2, $out['notices'] );
		$this->assertStringContainsString( 'FULLTEXT', $out['notices'][0] );
		$this->assertStringContainsString( 'FOREIGN KEY', $out['notices'][1] );
		$this->assertStringNotContainsString( 'FULLTEXT', $out['table'] );
		$this->assertStringNotContainsString( 'REFERENCES', $out['table'] );
	}

	public function test_constraint_unique_kept_as_unique_key(): void {
		$ddl = "CREATE TABLE `wp_u1` (\n"
			. "\t`a` int NOT NULL,\n"
			. "\t`b` int NOT NULL,\n"
			. "\tCONSTRAINT `wp_u1_constraint_1` UNIQUE KEY (`a`,`b`)\n"
			. ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4";
		$out = SchemaStage::stage( $ddl );
		$this->assertStringContainsString( 'UNIQUE ("a", "b")', $out['table'] );
		$this->assertCount( 0, $out['notices'] );
	}

	public function test_last_fixture_line_comma_fixed_without_elements(): void {
		$ddl = "CREATE TABLE `wp_noindex` (\n"
			. "\t`a` int NOT NULL,\n"
			. "\t`b` int NOT NULL\n"
			. ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4";
		$out = SchemaStage::stage( $ddl );
		$this->assertStringContainsString( '"a" ' === '' ? 'x' : '"a"', $out['table'] );
		$this->assertStringNotContainsString( ',)', $out['table'] );
		$this->assertCount( 0, $out['extra'] );
	}

	public function test_spatial_notice(): void {
		$ddl = "CREATE TABLE `wp_s1` (\n"
			. "\t`loc` point NOT NULL,\n"
			. "\tSPATIAL KEY `loc_idx` (`loc`),\n"
			. "\t`b` int NOT NULL\n"
			. ") ENGINE=InnoDB";
		$out = SchemaStage::stage( $ddl );
		$this->assertCount( 2, $out['notices'] );
		$this->assertStringContainsString( 'SPATIAL', $out['notices'][1] );
		$this->assertSame( array( 'loc' ), $out['skip_columns'] );
		$this->assertStringNotContainsString( '"loc"', $out['table'] );
		$this->assertStringContainsString( '"b"', $out['table'] );
	}
}
