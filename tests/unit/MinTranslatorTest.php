	/**
	 * S-01: a text column compared with a number works in MySQL and is
	 * refused by PostgreSQL; the literal is coerced instead. The whole
	 * statement must come out clean: two rewrite rules used to target the
	 * same literal and the second one mangled the output of the first
	 * (audit D-72).
	 */
	public function test_text_column_compared_with_a_number_is_coerced(): void {
		$cat = \Slonik\Schema\Catalog::fromRows(
			array(
