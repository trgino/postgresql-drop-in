<?php
declare( strict_types=1 );

namespace Slonik\Tests\Unit;

use PHPUnit\Framework\TestCase;
use Slonik\Schema\Catalog;
use Slonik\Sql\ExecutionPlan;
use Slonik\Sql\MinTranslator;
use Slonik\Sql\TranslationException;

final class MinTranslatorTest extends TestCase {

	private static function step_sql( $plan ) {
		$out = array();
		foreach ( $plan->getSteps() as $step ) {
			$out[] = $step->getSql();
		}
		return $out;
	}

	public function test_select_dispatch(): void {
		$t = MinTranslator::translate( 'SELECT a FROM t LIMIT 1, 2' );
		$this->assertSame( ExecutionPlan::KIND_SELECT, $t->getKind() );
		$this->assertSame( array( 'SELECT "a" FROM "t" LIMIT 2 OFFSET 1' ), self::step_sql( $t ) );
	}

	public function test_set_is_noop(): void {
		$t = MinTranslator::translate( "SET SESSION sql_mode='X'" );
		$this->assertSame( ExecutionPlan::KIND_NOOP, $t->getKind() );
		$this->assertSame( array(), self::step_sql( $t ) );
	}

	public function test_show_dispatch(): void {
		$t = MinTranslator::translate( 'SHOW TABLES' );
		$this->assertSame( ExecutionPlan::KIND_SHOW, $t->getKind() );
		$this->assertCount( 1, $t->getSteps() );
	}

	/**
	 * D-55: the SHOW VARIABLES probe is a query; the emulated row
	 * carries the MySQL column names (wordfence reads $rec['Value']).
	 */
	public function test_show_variables_dispatch(): void {
		$t = MinTranslator::translate( "SHOW VARIABLES LIKE 'max_allowed_packet'" );
		$this->assertSame( ExecutionPlan::KIND_SHOW, $t->getKind() );
		$this->assertSame(
			array( 'SELECT \'max_allowed_packet\' AS "Variable_name", \'67108864\' AS "Value"' ),
			self::step_sql( $t )
		);
	}

	public function test_ddl_dispatch(): void {
		$t = MinTranslator::translate( 'CREATE TABLE t (ID bigint(20) NOT NULL auto_increment, PRIMARY KEY (ID))' );
		$this->assertSame( ExecutionPlan::KIND_DDL, $t->getKind() );
		$this->assertStringContainsString( 'GENERATED BY DEFAULT AS IDENTITY', self::step_sql( $t )[0] );

		$t = MinTranslator::translate( 'DROP TABLE IF EXISTS wp_x' );
		$this->assertSame( ExecutionPlan::KIND_DDL, $t->getKind() );
		$this->assertSame( array( 'DROP TABLE IF EXISTS "wp_x"' ), self::step_sql( $t ) );

		$t = MinTranslator::translate( 'TRUNCATE TABLE wp_x' );
		$this->assertSame( ExecutionPlan::KIND_DDL, $t->getKind() );
		$this->assertSame( array( 'TRUNCATE TABLE "wp_x"' ), self::step_sql( $t ) );
	}

	/**
	 * D-79: ALTER TABLE reuses the KIND_DDL kind, where the runtime
	 * answers with the upstream truthy value and reloads the catalog.
	 */
	public function test_alter_table_dispatch(): void {
		$t = MinTranslator::translate( "ALTER TABLE wp_wfhits ADD COLUMN `attackLogTime` double(15,4) NOT NULL AFTER `id`" );
		$this->assertSame( ExecutionPlan::KIND_DDL, $t->getKind() );
		$this->assertSame(
			array(
				'ALTER TABLE "wp_wfhits" ADD COLUMN "attackLogTime" double precision NOT NULL',
				'COMMENT ON COLUMN "wp_wfhits"."attackLogTime" IS \'{"mysql":"double(15,4)"}\'',
			),
			self::step_sql( $t )
		);
	}

	public function test_alter_table_unsupported_fails_loud_at_the_boundary(): void {
		$this->expectException( TranslationException::class );
		MinTranslator::translate( 'ALTER TABLE wp_t DROP COLUMN c' );
	}

	public function test_plain_dml_dispatch(): void {
		$t = MinTranslator::translate( "INSERT INTO t (a) VALUES ('x')" );
		$this->assertSame( ExecutionPlan::KIND_INSERT, $t->getKind() );
		$this->assertSame( array( 'INSERT INTO "t" ("a") VALUES (\'x\')' ), self::step_sql( $t ) );
		$t = MinTranslator::translate( 'UPDATE t SET a = 1 WHERE b = 2' );
		$this->assertSame( ExecutionPlan::KIND_UPDATE, $t->getKind() );
		$this->assertSame( array( 'UPDATE "t" SET "a" = 1 WHERE "b" = 2' ), self::step_sql( $t ) );
		$t = MinTranslator::translate( 'DELETE FROM t WHERE a = 1' );
		$this->assertSame( ExecutionPlan::KIND_DELETE, $t->getKind() );
		$this->assertSame( array( 'DELETE FROM "t" WHERE "a" = 1' ), self::step_sql( $t ) );
	}

	//
	// M7.2: parameterization is opt-in via the 'parametrize' option.
	//
	public function test_translate_without_parametrize_is_unchanged(): void {
		$t = MinTranslator::translate( "SELECT * FROM t WHERE name = 'alice' AND age = 30" );
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "name" = \'alice\' AND "age" = 30' ), self::step_sql( $t ) );
		$this->assertSame( array(), $t->getSteps()[0]->getParams() );
	}

	public function test_parametrize_replaces_literals_with_placeholders(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE name = 'alice' AND age = 30",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "name" = $1 AND "age" = $2' ), self::step_sql( $t ) );
		$this->assertSame( array( 'alice', '30' ), $t->getSteps()[0]->getParams() );
	}

	public function test_parametrize_keeps_identifiers_and_keywords_intact(): void {
		$t = MinTranslator::translate(
			'SELECT `ID`, `post_title` FROM `wp_posts` WHERE `post_status` = \'publish\' LIMIT 5',
			null,
			array( 'parametrize' => true )
		);
		$sql = self::step_sql( $t );
		$this->assertStringContainsString( '"ID"', $sql[0] );
		$this->assertStringContainsString( '"post_title"', $sql[0] );
		$this->assertStringContainsString( '"wp_posts"', $sql[0] );
		$this->assertStringContainsString( '"post_status"', $sql[0] );
		$this->assertSame( array( 'publish', '5' ), $t->getSteps()[0]->getParams() );
	}

	public function test_insert_parametrize_captures_values(): void {
		$t = MinTranslator::translate(
			"INSERT INTO t (a, b) VALUES ('x', 7)",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( array( 'INSERT INTO "t" ("a", "b") VALUES ($1, $2)' ), self::step_sql( $t ) );
		$this->assertSame( array( 'x', '7' ), $t->getSteps()[0]->getParams() );
	}

	//
	// M7.3: IN-list normalization collapses every list length into one
	// statement shape so the prepared-statement cache reuses one plan.
	//
	public function test_in_list_normalizes_to_any_int(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE id IN (1,2,3)",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "id" = ANY($1::int[])' ), self::step_sql( $t ) );
		$this->assertSame( array( '{1,2,3}' ), $t->getSteps()[0]->getParams() );
	}

	public function test_in_list_different_lengths_share_shape(): void {
		$t1 = MinTranslator::translate(
			"SELECT * FROM t WHERE id IN (1,2)",
			null,
			array( 'parametrize' => true )
		);
		$t2 = MinTranslator::translate(
			"SELECT * FROM t WHERE id IN (1,2,3,4)",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( $t1->getSteps()[0]->getSql(), $t2->getSteps()[0]->getSql() );
		$this->assertSame( 'SELECT * FROM "t" WHERE "id" = ANY($1::int[])', $t1->getSteps()[0]->getSql() );
		$this->assertSame( array( '{1,2}' ), $t1->getSteps()[0]->getParams() );
		$this->assertSame( array( '{1,2,3,4}' ), $t2->getSteps()[0]->getParams() );
	}

	public function test_not_in_normalizes_to_all(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE id NOT IN (1,2,3)",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "id" <> ALL($1::int[])' ), self::step_sql( $t ) );
		$this->assertSame( array( '{1,2,3}' ), $t->getSteps()[0]->getParams() );
	}

	public function test_in_list_strings_normalize_to_text(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE name IN ('a','b')",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( array( "SELECT * FROM \"t\" WHERE \"name\" = ANY($1::text[])" ), self::step_sql( $t ) );
		$this->assertSame( array( '{"a","b"}' ), $t->getSteps()[0]->getParams() );
	}

	public function test_in_list_mixed_types_not_normalized(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE id IN (1,'x')",
			null,
			array( 'parametrize' => true )
		);
		// Mixed int + string: not normalized; IN stays, each literal parameterized.
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "id" IN ($1,$2)' ), self::step_sql( $t ) );
		$this->assertSame( array( '1', 'x' ), $t->getSteps()[0]->getParams() );
	}

	public function test_in_list_subquery_not_normalized(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE id IN (SELECT id FROM u)",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "id" IN (SELECT "id" FROM "u")' ), self::step_sql( $t ) );
		$this->assertSame( array(), $t->getSteps()[0]->getParams() );
	}

	public function test_in_list_combined_with_other_literal_orders_params(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE id IN (1,2) AND name = 'x'",
			null,
			array( 'parametrize' => true )
		);
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "id" = ANY($1::int[]) AND "name" = $2' ), self::step_sql( $t ) );
		$this->assertSame( array( '{1,2}', 'x' ), $t->getSteps()[0]->getParams() );
	}

	public function test_in_list_negative_literal_not_normalized(): void {
		$t = MinTranslator::translate(
			"SELECT * FROM t WHERE id IN (-1,-2)",
			null,
			array( 'parametrize' => true )
		);
		// Unary minus is a separate token: bail out of ANY() (it would drop
		// the sign); literal parameterization keeps `-$1` / `-$2` correct.
		$this->assertSame( array( 'SELECT * FROM "t" WHERE "id" IN (-$1,-$2)' ), self::step_sql( $t ) );
		$this->assertSame( array( '1', '2' ), $t->getSteps()[0]->getParams() );
	}

	//
	// R-063: MySQL's FROM DUAL has no PostgreSQL equivalent (the dummy
	// table does not exist). The Action Scheduler writes
	// INSERT ... SELECT ... FROM DUAL WHERE ( SELECT NULL FROM DUAL ) IS NULL
	// (WooCommerce), so the clause is removed instead of failing.
	//
	public function test_from_dual_is_removed(): void {
		$t = MinTranslator::translate( 'SELECT 1 FROM DUAL' );
		$this->assertSame( array( 'SELECT 1' ), self::step_sql( $t ) );

		$t = MinTranslator::translate( 'INSERT INTO t (a, b) SELECT ?, ? FROM DUAL WHERE ( SELECT NULL FROM DUAL ) IS NULL' );
		$this->assertSame(
			array( 'INSERT INTO "t" ("a", "b") SELECT ?, ? WHERE ( SELECT NULL ) IS NULL' ),
			self::step_sql( $t )
		);
	}

