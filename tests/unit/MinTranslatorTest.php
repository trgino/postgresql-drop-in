	/**
	 * A catalog with the same column name in two tables: wp_posts.ID and
	 * wp_wfhits.id are different columns, and another table has a column
	 * named P that must not touch the alias p.
	 *
	 * @return Catalog
	 */
	private static function case_catalog() {
		return Catalog::fromRows(
			array(
				array( 'table' => 'wp_wfhits', 'column' => 'id', 'nullable' => false, 'default' => null, 'pgtype' => 'bigint' ),
				array( 'table' => 'wp_posts', 'column' => 'ID', 'nullable' => false, 'default' => null, 'pgtype' => 'bigint' ),
				array( 'table' => 'wp_posts', 'column' => 'post_title', 'nullable' => false, 'default' => '', 'pgtype' => 'text' ),
				array( 'table' => 'wp_other', 'column' => 'P', 'nullable' => false, 'default' => null, 'pgtype' => 'bigint' ),
			),
			array()
		);
	}

	/**
	 * D-80: a column resolves against the statement's own table, not
	 * against the first table in the catalog that has a column with that
	 * name. The flat map picked whichever came first, so wp_posts.ID went
	 * out as "id" and PostgreSQL rejected the statement.
	 */
	public function test_column_case_resolves_against_the_statements_table(): void {
		$t = MinTranslator::translate( 'SELECT id FROM wp_posts', self::case_catalog() );
		$this->assertSame( array( 'SELECT "ID" FROM "wp_posts"' ), self::step_sql( $t ) );
	}

	public function test_qualified_column_resolves_through_the_alias(): void {
		$t = MinTranslator::translate( 'SELECT p.id FROM wp_posts p', self::case_catalog() );
		$this->assertSame( array( 'SELECT "p"."ID" FROM "wp_posts" "p"' ), self::step_sql( $t ) );
	}

	public function test_joined_columns_resolve_against_their_own_table(): void {
		$t = MinTranslator::translate(
			'SELECT p.id, h.id FROM wp_posts p INNER JOIN wp_wfhits h ON h.id = p.id',
			self::case_catalog()
		);
		$this->assertSame(
			array( 'SELECT "p"."ID", "h"."id" FROM "wp_posts" "p" INNER JOIN "wp_wfhits" "h" ON "h"."id" = "p"."ID"' ),
			self::step_sql( $t )
		);
	}

	public function test_subquery_columns_resolve_against_their_own_table(): void {
		$t = MinTranslator::translate(
			'SELECT p.id FROM wp_posts p WHERE p.id IN (SELECT h.id FROM wp_wfhits h)',
			self::case_catalog()
		);
		$this->assertSame(
			array( 'SELECT "p"."ID" FROM "wp_posts" "p" WHERE "p"."ID" IN (SELECT "h"."id" FROM "wp_wfhits" "h")' ),
			self::step_sql( $t )
		);
	}

	public function test_update_resolves_against_the_target_table(): void {
