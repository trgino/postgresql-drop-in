	/**
	 * A table alias is not a column: it keeps the written spelling even
	 * when another table has a column with the same name.
	 */
	public function test_alias_keeps_its_written_spelling(): void {
		$t = MinTranslator::translate( 'SELECT p.id FROM wp_posts p', self::case_catalog() );
		$this->assertStringContainsString( '"p"."ID" FROM "wp_posts" "p"', self::step_sql( $t )[0] );
	}

	/**
	 * The ORDER BY belongs to the query block, so its column resolves
